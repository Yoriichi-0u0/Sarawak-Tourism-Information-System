import { chromium } from "playwright-core";
const base = process.env.STIS_QA_BASE ?? "http://127.0.0.1:4173";
const browser = await chromium.launch(process.env.STIS_QA_BROWSER ? { executablePath: process.env.STIS_QA_BROWSER } : {});
const out = [];
const ok = (name, cond, detail = "") => out.push(`${cond ? "PASS" : "FAIL"} ${name}${detail ? ` — ${detail}` : ""}`);
const active = (page) => page.evaluate(() => ({ tag: document.activeElement?.tagName, cls: document.activeElement?.className, id: document.activeElement?.id, text: document.activeElement?.textContent?.trim().slice(0, 30), aria: document.activeElement?.getAttribute("aria-label") }));
let page = await (await browser.newContext({ viewport: { width: 1366, height: 900 } })).newPage();
await page.goto(`${base}/destinations`, { waitUntil: "networkidle" });
await page.keyboard.press("Tab");
let a = await active(page);
const top = await page.evaluate(() => document.querySelector(".skip-link").getBoundingClientRect().top);
ok("first Tab reaches a visible skip link", a.cls === "skip-link" && top >= 0, `top=${top}`);
await page.keyboard.press("Enter");
a = await active(page);
ok("skip link moves focus to main", a.id === "main");
await page.keyboard.press("Tab");
a = await active(page);
ok("next Tab enters page content", a.tag === "INPUT" || a.tag === "A" || a.tag === "BUTTON", JSON.stringify(a));
await page.locator('input[name=theme][value=auto]').focus();
await page.keyboard.press("ArrowRight");
const theme = await page.evaluate(() => document.documentElement.getAttribute("data-theme"));
ok("arrow keys change the theme radio group", theme === "light", `data-theme=${theme}`);
await page.keyboard.press("ArrowRight");
ok("dark theme applies", (await page.evaluate(() => document.documentElement.getAttribute("data-theme"))) === "dark");
await page.reload({ waitUntil: "networkidle" });
ok("theme choice persists across reload", (await page.evaluate(() => document.documentElement.getAttribute("data-theme"))) === "dark");
await page.locator('input[name=theme][value=auto]').check();
const storage = await page.evaluate(() => Object.keys(localStorage));
ok("only the theme key may be stored; Auto clears it", storage.length === 0, JSON.stringify(storage));
await page.goto(`${base}/stay`, { waitUntil: "networkidle" });
await page.locator(".card button").first().focus();
await page.keyboard.press("Enter");
await page.getByRole("dialog").waitFor();
a = await active(page);
ok("Add to trip dialog takes focus", await page.evaluate(() => Boolean(document.activeElement?.closest("[role=dialog]"))), JSON.stringify(a));
await page.keyboard.press("Escape");
await page.waitForTimeout(200);
ok("Escape closes the dialog and focus returns", !(await page.getByRole("dialog").count()) && (await active(page)).text?.includes("Add to trip"), JSON.stringify(await active(page)));
page = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage();
await page.goto(`${base}/`, { waitUntil: "networkidle" });
const menu = page.getByRole("button", { name: "Open menu" });
await menu.focus(); await page.keyboard.press("Enter");
ok("mobile menu opens from the keyboard", (await page.getByRole("button", { name: "Close menu" }).getAttribute("aria-expanded")) === "true");
await page.keyboard.press("Tab");
a = await active(page);
ok("Tab moves into the opened menu", a.tag === "A" && a.text === "Destinations", JSON.stringify(a));
await page.keyboard.press("Enter");
await page.waitForURL(/destinations/);
ok("menu closes after navigating", (await page.locator("#mobile-nav").getAttribute("data-open")) === "false");
console.log(out.join("\n"));
await browser.close();
