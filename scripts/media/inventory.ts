// Writes docs/full-system/media.md from the media library and the curated catalogue.
// Usage: node --import tsx scripts/media/inventory.ts
import { writeFileSync } from "node:fs";

import { catalogue } from "../../server/content/catalogue.ts";
import { mediaLibrary, mediaRole, type MediaAsset } from "../../src/shared/media.ts";

const used = (asset: MediaAsset) => catalogue.filter((record) => record.fields.image === asset.id)
  .map((record) => `${record.id}${mediaRole(asset, record.id) === "exact" ? "" : " (rep.)"}`).join(", ") || "home hero";
const rows = mediaLibrary.map((asset) => `| \`${asset.id}\` | ${asset.subject} | ${asset.kind === "photo"
  ? `[${asset.title.replace(/\|/g, "\\|")}](${asset.sourceUrl})` : "Local generated asset"} | ${asset.author} | ${asset.licence} | ${used(asset)} |`);
const unimaged = catalogue.filter((record) => !record.fields.image).map((record) => record.id);

writeFileSync("docs/full-system/media.md", `# Media inventory and policy

Generated by \`scripts/media/inventory.ts\` from \`src/shared/mediaLibrary.ts\`, which \`scripts/media/build.py\` builds from \`scripts/media/sources.json\`. To rebuild, run \`python3 -I scripts/media/build.py --cache <folder outside the repo>\`. The build checks every licence again through the Commons API and stops if one is not accepted.

## Policy (owner instruction, 24 Nov 2026)

1. **Source order:** (1) the Sarawak Tourism Board gallery, (2) Wikimedia Commons, after checking each file's licence and author, (3) other sources with explicit reuse licences, (4) generated images, only where no licensed photo exists.
2. **Matching:** a photo is shown as a picture of a listing only if the manifest lists that record in its \`recordIds\`, and a test enforces this. Any other use is captioned *Representative photo … Not a photo of this listing*. Every destination must have a picture of itself.
3. **Fictional listings:** demonstration listings never get an exact photo. AI illustrations are labelled *AI illustration* and never stand in for real places.
4. **No hotlinking:** images are re-encoded locally as AVIF and WebP at 480, 960 and 1600 px, with EXIF and XMP removed. They are served responsively, with intrinsic sizes and lazy loading.
5. **Credits:** every image is credited in its detail caption and on \`/credits\`. Resized and cropped versions of CC BY-SA photos are shared under the same licence.
6. **Publishing:** staff can publish only images from the library. An unknown image blocks publication, so uncredited or hotlinked images cannot go live.

## Sarawak Tourism Board gallery

The gallery's licence page says CC0 but adds conditions: no commercial use, credit the owner shown on each photo, and do not show identifiable people in a bad light. Downloads require a member login, and the page disables right-click. STIS therefore uses none of its photos yet, because taking the on-page preview images would get around the download control. If the owner registers and downloads chosen photos, they can be added through \`sources.json\` as local sources, with the stated credit and a non-commercial restriction. They would have to be replaced if STIS ever became commercial.

## Retired assets

The eleven generated images in \`public/images\` from the first prototype (commit \`164b7b1\`) have been removed. Several were invented likenesses of real places: the "Borneo Cultures Museum" image showed a building that does not exist, and one generated cave stood in for both Mulu and Niah. Two neutral images, a hotel room and a cafe, are kept as labelled illustrations for demonstration listings.

## Inventory (${mediaLibrary.length} images)

| ID | Subject | Source | Author | Licence | Used by (rep. = representative) |
|---|---|---|---|---|---|
${rows.join("\n")}

Records without an image show their category icon: ${unimaged.join(", ")}.
`);
console.log(`${rows.length} images, ${unimaged.length} records without images`);
